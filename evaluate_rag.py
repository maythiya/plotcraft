def metrics(retrieved, relevant):
    if not retrieved: return 0.0, 0.0, 0.0
    tp = len(retrieved & relevant)
    p  = tp / len(retrieved)
    r  = tp / len(relevant) if relevant else 0.0
    f1 = (2*p*r/(p+r)) if (p+r) > 0 else 0.0
    return p, r, f1

